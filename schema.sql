-- Drop existing tables (run this in Supabase SQL Editor)
DROP TABLE IF EXISTS employee CASCADE;
DROP TABLE IF EXISTS visitors CASCADE;
DROP TABLE IF EXISTS vehicle CASCADE;

-- Employee table with auto-increment ID
CREATE TABLE employee (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text,
    phone text,
    login_id text UNIQUE,
    password text,
    Auth_level integer,
    status integer DEFAULT 0,
    connection_mode text,
    public_url text,
    last_seen timestamp with time zone,
    created_at timestamp with time zone DEFAULT now() NOT NULL
);

-- Visitors table with auto-increment ID
CREATE TABLE visitors (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text,
    phone text,
    person_to_visit text,
    reason text,
    has_vehicle boolean DEFAULT false,
    vehicle_number text,
    entry_time timestamp with time zone DEFAULT now(),
    exit_time timestamp with time zone,
    status integer DEFAULT 0,
    denial_reason text,
    id_type text,
    id_number text,
    added_by text,
    updated_at timestamp with time zone DEFAULT now(),
    created_at timestamp with time zone DEFAULT now() NOT NULL
);

-- Vehicle/Logistics table with auto-increment ID
CREATE TABLE vehicle (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    driver_name text,
    veh_reg_no text,
    vehicle_img text,
    destination text,
    "time" timestamp with time zone DEFAULT now(),
    driver_phone text,
    origin text,
    purchase_no text,
    entry_type text DEFAULT 'Entry',
    tare_weight numeric,
    is_returnable integer DEFAULT 0,
    material_type text,
    return_reason text,
    driver_id_type text,
    driver_id_number text,
    vehicle_length text,
    return_time text,
    created_at timestamp with time zone DEFAULT now() NOT NULL
);

-- Enable Row Level Security (but allow all operations for now)
ALTER TABLE employee ENABLE ROW LEVEL SECURITY;
ALTER TABLE visitors ENABLE ROW LEVEL SECURITY;
ALTER TABLE vehicle ENABLE ROW LEVEL SECURITY;

-- Create policies to allow all operations (adjust for production)
CREATE POLICY "Allow all operations on employee" ON employee FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow all operations on visitors" ON visitors FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow all operations on vehicle" ON vehicle FOR ALL USING (true) WITH CHECK (true);